func generatePackage(
	targetNames []string,
	output, buildConstraint string,
	diagnostics io.Writer,
) error {
	if diagnostics == nil {
		diagnostics = io.Discard
	}
	absOutput, err := filepath.Abs(output)
	if err != nil {
		return err
	}
	generatedFiles, err := findGeneratedFiles(absOutput)
	if err != nil {
		return err
	}
	liveTypes, handwrittenMethods, activeGeneratedFiles, typeAliases, err := loadPackageSyntax(
		generatedFiles,
		diagnostics,
	)
	if err != nil {
		return err
	}
	overlay, err := signatureOverlay(
		generatedFiles,
		liveTypes,
		handwrittenMethods,
		activeGeneratedFiles,
		typeAliases,
		nil,
	)
	if err != nil {
		return err
	}

	cfg := &packages.Config{
		ParseFile: parsePackageFile,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesSizes | packages.NeedModule |
			packages.NeedImports | packages.NeedExportFile,
		Overlay: overlay,
		Tests:   false,
	}
	pkgs, err := packages.Load(cfg, ".", mmdbdataPath)
	if err != nil {
		return err
	}
	if writePackageErrors(diagnostics, pkgs) != 0 {
		for _, pkg := range pkgs {
			if pkg.PkgPath == mmdbdataPath {
				continue
			}
			for _, err := range pkg.Errors {
				if err.Kind == packages.ParseError {
					return errors.New("loading target package syntax")
				}
			}
		}
		return errors.New("loading target package")
	}
	var targetPackage, mmdbdataPackage *packages.Package
	for _, loaded := range pkgs {
		if loaded.PkgPath == mmdbdataPath {
			mmdbdataPackage = loaded
		} else {
			targetPackage = loaded
		}
	}
	if targetPackage == nil || mmdbdataPackage == nil {
		return fmt.Errorf("loading target and %s packages", mmdbdataPath)
	}
	unmarshaler, err := packageInterface(mmdbdataPackage.Types, "Unmarshaler")
	if err != nil {
		return err
	}
	cursorDecoder, err := packageInterface(mmdbdataPackage.Types, "CursorUnmarshaler")
	if err != nil {
		return err
	}

	g := &generator{
		pkg:             targetPackage,
		mmdbdata:        mmdbdataPackage,
		structs:         make(map[*types.Named]structInfo),
		visiting:        make(map[*types.Named]bool),
		targetSet:       make(map[*types.Named]bool),
		generatedFiles:  generatedFileSet(generatedFiles),
		importPackages:  make(map[string]*types.Package),
		importNames:     make(map[string]string),
		unmarshaler:     unmarshaler,
		cursorDecoder:   cursorDecoder,
		helperNamespace: encodeHelperNamespace(absOutput),
	}
	if err := g.addTargets(targetNames, diagnostics); err != nil {
		return err
	}

	for _, target := range g.targets {
		if err := g.analyzeStruct(target); err != nil {
			return err
		}
	}
	if err := g.validateHelperNames(); err != nil {
		return err
	}
	g.prepareImports()
	g.prepareLocalNames()
	if err := g.checkShadowedBuiltins(); err != nil {
		return err
	}
	source, err := g.render(buildConstraint)
	if err != nil {
		return err
	}
	err = g.validateGeneratedPackage(
		absOutput,
		source,
		generatedFiles,
		liveTypes,
		handwrittenMethods,
		activeGeneratedFiles,
		typeAliases,
		diagnostics,
	)
	if err != nil {
		return err
	}
	return writeAtomic(absOutput, source)
}

func (g *generator) addTargets(targetNames []string, diagnostics io.Writer) error {
	seenTargets := make(map[string]bool)
	for _, name := range targetNames {
		if seenTargets[name] {
			return fmt.Errorf("duplicate target type %q", name)
		}
		seenTargets[name] = true
		obj := g.pkg.Types.Scope().Lookup(name)
		if obj == nil {
			return fmt.Errorf("type %q is not declared in package %s", name, g.pkg.PkgPath)
		}
		typeName, ok := obj.(*types.TypeName)
		if !ok {
			return g.positionError(obj.Pos(), "%q is not a type", name)
		}
		named, ok := typeName.Type().(*types.Named)
		if !ok {
			return g.positionError(obj.Pos(), "%q is not a named type", name)
		}
		if _, ok := named.Underlying().(*types.Struct); !ok {
			return g.positionError(obj.Pos(), "target %s is not a struct", name)
		}
		if method := lookupUnmarshalMethod(named); method != nil && !g.isGeneratedMethod(method) {
			if g.implements(named, g.unmarshaler) {
				_, err := fmt.Fprintf(
					diagnostics,
					"maxminddb-gen: skipping %s: handwritten UnmarshalMaxMindDB method\n",
					name,
				)
				if err != nil {
					return err
				}
				continue
			}
			return g.positionError(
				method.Pos(),
				"type %s has an incompatible UnmarshalMaxMindDB method; want func(*mmdbdata.Decoder) error",
				name,
			)
		}
		if method := lookupCursorUnmarshalMethod(named); method != nil &&
			!g.isGeneratedMethod(method) {
			if g.implements(named, g.cursorDecoder) {
				_, err := fmt.Fprintf(
					diagnostics,
					"maxminddb-gen: skipping %s: handwritten UnmarshalMaxMindDBCursor method\n",
					name,
				)
				if err != nil {
					return err
				}
				continue
			}
			return g.positionError(
				method.Pos(),
				"type %s has an incompatible UnmarshalMaxMindDBCursor method; want func(mmdbdata.Cursor) (mmdbdata.Cursor, error)",
				name,
			)
		}
		if named.TypeParams().Len() != 0 {
			return g.positionError(obj.Pos(), "generic target %s is not supported", name)
		}
		g.targets = append(g.targets, named)
		g.targetSet[named] = true
	}
	if len(g.targets) == 0 {
		return errors.New("no decoders remain after excluding types with handwritten methods")
	}
	return nil
}

func findGeneratedFiles(path string) ([]priorGeneratedFile, error) {
	files := make([]priorGeneratedFile, 0)
	path = filepath.Clean(path)
	contents, err := os.ReadFile(path)
	if err == nil {
		file, generated, parseErr := parseGeneratedFile(token.NewFileSet(), path, contents)
		if parseErr != nil {
			return nil, parseErr
		}
		if !generated {
			return nil, fmt.Errorf("output %s exists and was not created by maxminddb-gen", path)
		}
		files = append(files, priorGeneratedFile{file: file, path: path})
	} else if !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}

	cwd, err := os.Getwd()
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(cwd)
	if err != nil {
		return nil, err
	}
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != goFileExtension ||
			strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		candidate := filepath.Clean(filepath.Join(cwd, entry.Name()))
		if candidate == path {
			continue
		}
		contents, err := os.ReadFile(candidate)
		if err != nil {
			return nil, err
		}
		if !strings.Contains(string(contents), generatedPrefix) {
			continue
		}
		file, generated, err := parseGeneratedFile(token.NewFileSet(), candidate, contents)
		if err != nil {
			return nil, err
		}
		if generated {
			files = append(files, priorGeneratedFile{file: file, path: candidate})
		}
	}
	return files, nil
}

func generatedFileSet(files []priorGeneratedFile) map[string]bool {
	paths := make(map[string]bool, len(files))
	for _, file := range files {
		paths[filepath.Clean(file.path)] = true
	}
	return paths
}

func loadPackageSyntax(
	generatedFiles []priorGeneratedFile,
	diagnostics io.Writer,
) (map[string]bool, map[methodKey]bool, map[string]bool, map[string]string, error) {
	// Only prior generated signatures need a separate syntax pass.
	if len(generatedFiles) == 0 {
		return nil, nil, nil, nil, nil
	}
	overlay := make(map[string][]byte, len(generatedFiles))
	generatedPaths := make(map[string]bool, len(generatedFiles))
	for _, generated := range generatedFiles {
		overlay[generated.path] = packageStub(generated.file)
		generatedPaths[generated.path] = true
	}
	pkgs, err := packages.Load(&packages.Config{
		ParseFile: parsePackageFile,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedSyntax,
		Overlay: overlay,
		Tests:   false,
	}, ".")
	if err != nil {
		return nil, nil, nil, nil, err
	}
	if writePackageErrors(diagnostics, pkgs) != 0 || len(pkgs) != 1 {
		return nil, nil, nil, nil, errors.New("loading target package syntax")
	}

	typeSpecs := make(map[string]*ast.TypeSpec)
	rawHandwrittenMethods := make([]methodKey, 0)
	pkg := pkgs[0]
	activeGeneratedFiles := make(map[string]bool)
	for _, filename := range pkg.CompiledGoFiles {
		filename = filepath.Clean(filename)
		if generatedPaths[filename] {
			activeGeneratedFiles[filename] = true
		}
	}
	for _, file := range pkg.Syntax {
		filename := filepath.Clean(pkg.Fset.Position(file.Package).Filename)
		if generatedPaths[filename] {
			continue
		}
		for _, declaration := range file.Decls {
			switch declaration := declaration.(type) {
			case *ast.GenDecl:
				if declaration.Tok != token.TYPE {
					continue
				}
				for _, spec := range declaration.Specs {
					typeSpec := spec.(*ast.TypeSpec)
					typeSpecs[typeSpec.Name.Name] = typeSpec
				}
			case *ast.FuncDecl:
				receiver := receiverTypeName(declaration)
				if receiver != "" {
					rawHandwrittenMethods = append(rawHandwrittenMethods, methodKey{
						receiver: receiver,
						name:     declaration.Name.Name,
					})
				}
			default:
			}
		}
	}
	liveTypes, typeAliases := receiverTypes(typeSpecs)
	handwrittenMethods := make(map[methodKey]bool, len(rawHandwrittenMethods))
	for _, method := range rawHandwrittenMethods {
		method.receiver = canonicalTypeName(method.receiver, typeAliases)
		handwrittenMethods[method] = true
	}
	return liveTypes, handwrittenMethods, activeGeneratedFiles, typeAliases, nil
}

func receiverTypes(typeSpecs map[string]*ast.TypeSpec) (map[string]bool, map[string]string) {
	liveTypes := make(map[string]bool)
	typeAliases := make(map[string]string)
	for name := range typeSpecs {
		canonical, ok := receiverType(name, typeSpecs, make(map[string]bool))
		if !ok {
			continue
		}
		liveTypes[canonical] = true
		if name != canonical {
			typeAliases[name] = canonical
		}
	}
	return liveTypes, typeAliases
}

func parsePackageFile(fset *token.FileSet, filename string, source []byte) (*ast.File, error) {
	// Package type checking uses neither comment nodes nor the parser's object map.
	return parser.ParseFile(
		fset,
		filename,
		source,
		parser.AllErrors|parser.SkipObjectResolution,
	)
}

func receiverType(
	name string,
	typeSpecs map[string]*ast.TypeSpec,
	seen map[string]bool,
) (string, bool) {
	if seen[name] {
		return "", false
	}
	seen[name] = true
	typeSpec, ok := typeSpecs[name]
	if !ok || typeSpec.TypeParams != nil {
		return "", false
	}
	if !typeSpec.Assign.IsValid() {
		if !receiverUnderlyingType(typeSpec.Type, typeSpecs, seen) {
			return "", false
		}
		return name, true
	}
	target, ok := unparenthesized(typeSpec.Type).(*ast.Ident)
	if !ok {
		return "", false
	}
	return receiverType(target.Name, typeSpecs, seen)
}

func receiverUnderlyingType(
	expression ast.Expr,
	typeSpecs map[string]*ast.TypeSpec,
	seen map[string]bool,
) bool {
	switch expression := unparenthesized(expression).(type) {
	case *ast.ArrayType, *ast.ChanType, *ast.FuncType, *ast.MapType, *ast.StructType:
		return true
	case *ast.Ident:
		if valid, known := predeclaredReceiverUnderlying(expression.Name); known {
			return valid
		}
		return receiverDeclaredUnderlying(expression.Name, false, typeSpecs, seen)
	case *ast.IndexExpr:
		return receiverIndexedUnderlying(expression.X, typeSpecs, seen)
	case *ast.IndexListExpr:
		return receiverIndexedUnderlying(expression.X, typeSpecs, seen)
	case *ast.InterfaceType, *ast.StarExpr:
		return false
	default:
		return false
	}
}

func receiverIndexedUnderlying(
	expression ast.Expr,
	typeSpecs map[string]*ast.TypeSpec,
	seen map[string]bool,
) bool {
	identifier, ok := unparenthesized(expression).(*ast.Ident)
	if !ok {
		return false
	}
	return receiverDeclaredUnderlying(identifier.Name, true, typeSpecs, seen)
}

func receiverDeclaredUnderlying(
	name string,
	instantiated bool,
	typeSpecs map[string]*ast.TypeSpec,
	seen map[string]bool,
) bool {
	if seen[name] {
		return false
	}
	typeSpec, ok := typeSpecs[name]
	if !ok || typeSpec.TypeParams != nil && !instantiated {
		return false
	}
	seen[name] = true
	return receiverUnderlyingType(typeSpec.Type, typeSpecs, seen)
}

func predeclaredReceiverUnderlying(name string) (valid, known bool) {
	switch name {
	case "bool", "byte", "complex64", "complex128", "float32", "float64",
		"int", "int8", "int16", "int32", "int64", "rune", "string",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr":
		return true, true
	case "any", "comparable", "error":
		return false, true
	default:
		return false, false
	}
}

func unparenthesized(expression ast.Expr) ast.Expr {
	for {
		parenthesized, ok := expression.(*ast.ParenExpr)
		if !ok {
			return expression
		}
		expression = parenthesized.X
	}
}

func signatureOverlay(
	generatedFiles []priorGeneratedFile,
	liveTypes map[string]bool,
	handwrittenMethods map[methodKey]bool,
	activeGeneratedFiles map[string]bool,
	typeAliases map[string]string,
	includedMethods map[methodKey]bool,
) (map[string][]byte, error) {
	overlay := make(map[string][]byte, len(generatedFiles))
	if includedMethods == nil {
		includedMethods = make(map[methodKey]bool)
	}
	for _, generated := range generatedFiles {
		if !activeGeneratedFiles[generated.path] {
			overlay[generated.path] = packageStub(generated.file)
			continue
		}
		methods := make([]*ast.FuncDecl, 0)
		for _, declaration := range generated.file.Decls {
			method, key, ok := exportedMethodKey(declaration, typeAliases)
			if !ok {
				continue
			}
			if !liveTypes[key.receiver] || handwrittenMethods[key] || includedMethods[key] {
				continue
			}
			methods = append(methods, method)
			includedMethods[key] = true
		}
		stub, err := signatureStub(generated.file, methods)
		if err != nil {
			return nil, err
		}
		overlay[generated.path] = stub
	}
	return overlay, nil
}

func receiverTypeName(method *ast.FuncDecl) string {
	if method.Recv == nil || len(method.Recv.List) != 1 {
		return ""
	}
	return baseTypeName(method.Recv.List[0].Type)
}

func baseTypeName(expression ast.Expr) string {
	switch expression := expression.(type) {
	case *ast.Ident:
		return expression.Name
	case *ast.StarExpr:
		return baseTypeName(expression.X)
	case *ast.IndexExpr:
		return baseTypeName(expression.X)
	case *ast.IndexListExpr:
		return baseTypeName(expression.X)
	default:
		return ""
	}
}

func canonicalTypeName(name string, aliases map[string]string) string {
	seen := make(map[string]bool)
	for {
		if seen[name] {
			return name
		}
		seen[name] = true
		next, ok := aliases[name]
		if !ok {
			return name
		}
		name = next
	}
}

func parseGeneratedFile(
	fset *token.FileSet,
	path string,
	contents []byte,
) (*ast.File, bool, error) {
	file, err := parser.ParseFile(
		fset,
		path,
		contents,
		parser.ParseComments|parser.SkipObjectResolution,
	)
	if err != nil {
		return nil, false, fmt.Errorf("reading package from prior output: %w", err)
	}
	for _, group := range file.Comments {
		if group.Pos() > file.Package {
			break
		}
		for _, comment := range group.List {
			if isGeneratedMarker(comment.Text) {
				return file, true, nil
			}
		}
	}
	return file, false, nil
}

func isGeneratedMarker(comment string) bool {
	const suffix = "; DO NOT EDIT."
	if comment == generatedPrefix+suffix {
		return true
	}
	prefix := generatedPrefix + " "
	if !strings.HasPrefix(comment, prefix) || !strings.HasSuffix(comment, suffix) {
		return false
	}
	version := comment[len(prefix) : len(comment)-len(suffix)]
	return version != "" && !strings.ContainsAny(version, " \t\r\n")
}

func packageStub(file *ast.File) []byte {
	return []byte(generatedBuildConstraints(file) + "package " + file.Name.Name + "\n")
}

func signatureStub(file *ast.File, methods []*ast.FuncDecl) ([]byte, error) {
	if len(methods) == 0 {
		return packageStub(file), nil
	}

	usedImports := make(map[string]bool)
	for _, method := range methods {
		for _, node := range []ast.Node{method.Recv, method.Type} {
			ast.Inspect(node, func(node ast.Node) bool {
				selector, ok := node.(*ast.SelectorExpr)
				if !ok {
					return true
				}
				identifier, ok := selector.X.(*ast.Ident)
				if ok {
					usedImports[identifier.Name] = true
				}
				return true
			})
		}
	}

	var source strings.Builder
	source.WriteString(generatedBuildConstraints(file))
	fmt.Fprintf(&source, "package %s\n\n", file.Name.Name)
	imports := make([]*ast.ImportSpec, 0)
	for _, imported := range file.Imports {
		name, err := generatedImportName(imported)
		if err != nil {
			return nil, err
		}
		if usedImports[name] {
			imports = append(imports, imported)
		}
	}
	if len(imports) > 0 {
		source.WriteString("import (\n")
		for _, imported := range imports {
			source.WriteByte('\t')
			if err := format.Node(&source, token.NewFileSet(), imported); err != nil {
				return nil, err
			}
			source.WriteByte('\n')
		}
		source.WriteString(")\n\n")
	}
	for _, method := range methods {
		stub := *method
		stub.Doc = nil
		stub.Body = &ast.BlockStmt{List: []ast.Stmt{&ast.ExprStmt{X: &ast.CallExpr{
			Fun: ast.NewIdent("panic"),
			Args: []ast.Expr{&ast.BasicLit{
				Kind:  token.STRING,
				Value: strconv.Quote("maxminddb-gen loading stub"),
			}},
		}}}}
		if err := format.Node(&source, token.NewFileSet(), &stub); err != nil {
			return nil, err
		}
		source.WriteString("\n\n")
	}
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("formatting prior generated signatures: %w", err)
	}
	return formatted, nil
}

func generatedImportName(imported *ast.ImportSpec) (string, error) {
	if imported.Name != nil {
		return imported.Name.Name, nil
	}
	path, err := strconv.Unquote(imported.Path.Value)
	if err != nil {
		return "", err
	}
	if path == mmdbdataPath {
		return "mmdbdata", nil
	}
	return filepath.Base(path), nil
}

func generatedBuildConstraints(file *ast.File) string {
	var constraints strings.Builder
	for _, group := range file.Comments {
		if group.Pos() > file.Package {
			break
		}
		for _, comment := range group.List {
			if strings.HasPrefix(comment.Text, "//go:build ") ||
				strings.HasPrefix(comment.Text, "// +build ") {
				constraints.WriteString(comment.Text)
				constraints.WriteByte('\n')
			}
		}
	}
	if constraints.Len() > 0 {
		constraints.WriteByte('\n')
	}
	return constraints.String()
}

func (g *generator) validateGeneratedPackage(
	path string,
	source []byte,
	generatedFiles []priorGeneratedFile,
	liveTypes map[string]bool,
	handwrittenMethods map[methodKey]bool,
	activeGeneratedFiles map[string]bool,
	typeAliases map[string]string,
	diagnostics io.Writer,
) error {
	file, generated, err := parseGeneratedFile(g.pkg.Fset, path, source)
	if err != nil {
		return err
	}
	if !generated {
		return errors.New("rendered output is missing its generated-code marker")
	}

	remainingFiles := make([]priorGeneratedFile, 0, len(generatedFiles))
	for _, existing := range generatedFiles {
		if existing.path != path {
			remainingFiles = append(remainingFiles, existing)
		}
	}
	overlay, err := signatureOverlay(
		remainingFiles,
		liveTypes,
		handwrittenMethods,
		activeGeneratedFiles,
		typeAliases,
		generatedMethodKeys(file, typeAliases),
	)
	if err != nil {
		return err
	}
	overlay[path] = source
	handled, err := validateLoadedPackage(
		g.pkg,
		g.mmdbdata,
		file,
		path,
		overlay,
		diagnostics,
	)
	if handled {
		return err
	}

	pkgs, err := packages.Load(&packages.Config{
		ParseFile: parsePackageFile,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesSizes,
		Overlay: overlay,
		Tests:   false,
	}, ".")
	if err != nil {
		return err
	}
	// An excluded output also leaves the package without its decoders, so
	// report the exclusion instead of the type errors that follow from it.
	if len(pkgs) == 1 && len(pkgs[0].CompiledGoFiles) > 0 &&
		!containsFile(pkgs[0].CompiledGoFiles, path) {
		return excludedOutputError(path)
	}
	if writePackageErrors(diagnostics, pkgs) != 0 || len(pkgs) != 1 {
		return errors.New("validating generated package")
	}
	if !containsFile(pkgs[0].CompiledGoFiles, path) {
		return excludedOutputError(path)
	}
	return nil
}

func excludedOutputError(path string) error {
	return fmt.Errorf(
		"output %q is excluded from the package build by its file name or build constraints",
		filepath.Base(path),
	)
}

// containsFile reports whether files names path, allowing for the go command
// spelling the package directory differently.
func containsFile(files []string, path string) bool {
	path = filepath.Clean(path)
	for _, file := range files {
		file = filepath.Clean(file)
		if file == path {
			return true
		}
		if filepath.Base(file) == filepath.Base(path) &&
			sameDirectory(filepath.Dir(file), filepath.Dir(path)) {
			return true
		}
	}
	return false
}

func writePackageErrors(diagnostics io.Writer, pkgs []*packages.Package) int {
	if diagnostics == nil {
		diagnostics = io.Discard
	}
	count := 0
	for _, pkg := range pkgs {
		for _, err := range pkg.Errors {
			_, _ = fmt.Fprintln(diagnostics, err)
			count++
		}
	}
	return count
}

func generatedMethodKeys(file *ast.File, typeAliases map[string]string) map[methodKey]bool {
	methods := make(map[methodKey]bool)
	for _, declaration := range file.Decls {
		_, key, ok := exportedMethodKey(declaration, typeAliases)
		if !ok {
			continue
		}
		methods[key] = true
	}
	return methods
}

func exportedMethodKey(
	declaration ast.Decl,
	typeAliases map[string]string,
) (*ast.FuncDecl, methodKey, bool) {
	method, ok := declaration.(*ast.FuncDecl)
	if !ok || method.Recv == nil || !method.Name.IsExported() {
		return nil, methodKey{}, false
	}
	return method, methodKey{
		receiver: canonicalTypeName(receiverTypeName(method), typeAliases),
		name:     method.Name.Name,
	}, true
}

type atomicOutputFile interface {
	Name() string
	Write([]byte) (int, error)
	Chmod(os.FileMode) error
	Sync() error
	Close() error
}

func writeAtomic(path string, contents []byte) error {
	return writeAtomicWith(
		path,
		contents,
		func(dir, pattern string) (atomicOutputFile, error) {
			return os.CreateTemp(dir, pattern)
		},
		replaceFile,
	)
}

func writeAtomicWith(
	path string,
	contents []byte,
	createTemp func(string, string) (atomicOutputFile, error),
	replace func(string, string) error,
) error {
	dir := filepath.Dir(path)
	temp, err := createTemp(dir, ".maxminddb-gen-*")
	if err != nil {
		return err
	}
	tempName := temp.Name()
	defer func() { _ = os.Remove(tempName) }()
	if _, err := temp.Write(contents); err != nil {
		_ = temp.Close()
		return err
	}
	if err := temp.Chmod(0o644); err != nil {
		_ = temp.Close()
		return err
	}
	if err := temp.Sync(); err != nil {
		_ = temp.Close()
		return err
	}
	if err := temp.Close(); err != nil {
		return err
	}
	return replace(tempName, path)
}

func (g *generator) analyzeStruct(named *types.Named) error {
	if named.TypeParams().Len() != 0 {
		return g.positionError(
			named.Obj().Pos(),
			"generic struct %s is not supported",
			named.Obj().Name(),
		)
	}
	if _, ok := g.structs[named]; ok {
		return nil
	}
	if g.visiting[named] {
		return g.positionError(
			named.Obj().Pos(),
			"recursive type graph through %s is not supported",
			named.Obj().Name(),
		)
	}
	g.visiting[named] = true
	defer delete(g.visiting, named)

	structure := named.Underlying().(*types.Struct)
	info := structInfo{named: named}
	seenNames := make(map[string]token.Pos)
	for i := range structure.NumFields() {
		field := structure.Field(i)
		if field.Embedded() {
			return g.positionError(
				field.Pos(),
				"embedded field %s is not yet supported",
				field.Name(),
			)
		}
		if !field.Exported() {
			continue
		}
		tag, tagged, err := maxminddbTag(structure.Tag(i))
		if err != nil {
			return g.positionError(field.Pos(), "field %s: %v", field.Name(), err)
		}
		if tag.Ignored {
			continue
		}
		name := field.Name()
		if tagged && tag.HasName {
			name = tag.Name
		}
		if previous, exists := seenNames[name]; exists {
			return g.positionError(
				field.Pos(),
				"field %s conflicts with another field at %s for MMDB key %q",
				field.Name(),
				g.pkg.Fset.Position(previous),
				name,
			)
		}
		seenNames[name] = field.Pos()
		plan, err := g.analyzeType(field.Type())
		if err != nil {
			return g.positionError(field.Pos(), "field %s: %v", field.Name(), err)
		}
		maxSizeKind, maxSizeSupported := maxSizeKindForPlan(plan)
		if tag.HasMaxSize && !maxSizeSupported {
			return g.positionError(
				field.Pos(),
				"field %s: maxsize is only supported for maps, slices, strings, and bytes",
				field.Name(),
			)
		}
		g.prepareInferredDecoder(plan)
		info.fields = append(
			info.fields,
			fieldInfo{
				plan:        plan,
				name:        name,
				goID:        field.Name(),
				maxSize:     tag.MaxSize,
				maxSizeKind: maxSizeKind,
				hasMaxSize:  tag.HasMaxSize,
			},
		)
	}
	g.structs[named] = info
	return nil
}

func (g *generator) analyzeType(t types.Type) (*decodePlan, error) {
	if alias, ok := t.(*types.Alias); ok {
		plan, err := g.analyzeType(types.Unalias(alias))
		if plan != nil {
			// An exported alias can name an unexported type in another package.
			plan.typ = t
		}
		return plan, err
	}
	if pointer, ok := t.(*types.Pointer); ok {
		elem, err := g.analyzeType(pointer.Elem())
		return &decodePlan{typ: t, kind: decodePointer, elem: elem}, err
	}
	if _, ok := t.Underlying().(*types.Interface); ok {
		return nil, fmt.Errorf("interface type %s is not supported", t)
	}
	if g.implements(t, g.cursorDecoder) {
		return &decodePlan{typ: t, kind: decodeCursorUnmarshaler}, nil
	}
	if g.implements(t, g.unmarshaler) {
		return &decodePlan{typ: t, kind: decodeUnmarshaler}, nil
	}
	switch value := t.(type) {
	case *types.Named:
		underlying := value.Underlying()
		if _, ok := underlying.(*types.Struct); ok {
			if value.Origin().TypeParams().Len() != 0 {
				return nil, fmt.Errorf("generic struct %s is not supported", value.Obj().Name())
			}
			if value.Obj().Pkg() != g.pkg.Types {
				return nil, fmt.Errorf(
					"struct type %s is owned by another package and does not implement mmdbdata.CursorUnmarshaler or mmdbdata.Unmarshaler",
					value,
				)
			}
			if err := g.analyzeStruct(value); err != nil {
				return nil, err
			}
			return &decodePlan{typ: t, kind: decodeStruct, named: value}, nil
		}
		if basic, ok := underlying.(*types.Basic); ok {
			if err := supportedBasic(basic); err != nil {
				return nil, err
			}
			return &decodePlan{typ: t, kind: decodeBasic, basic: basic}, nil
		}
		if g.visiting[value] {
			return nil, fmt.Errorf(
				"recursive type graph through %s is not supported",
				value.Obj().Name(),
			)
		}
		g.visiting[value] = true
		defer delete(g.visiting, value)
		plan, err := g.analyzeType(underlying)
		if plan != nil && plan.kind == decodeBytes {
			plan = &decodePlan{typ: t, kind: decodeSlice, elem: plan.elem}
		} else if plan != nil {
			plan.typ = t
		}
		return plan, err
	case *types.Basic:
		if err := supportedBasic(value); err != nil {
			return nil, err
		}
		return &decodePlan{typ: t, kind: decodeBasic, basic: value}, nil
	case *types.Slice:
		if types.Identical(t, types.NewSlice(types.Typ[types.Byte])) {
			elem, err := g.analyzeType(value.Elem())
			return &decodePlan{typ: t, kind: decodeBytes, elem: elem}, err
		}
		elem, err := g.analyzeType(value.Elem())
		return &decodePlan{typ: t, kind: decodeSlice, elem: elem}, err
	case *types.Map:
		key, ok := value.Key().Underlying().(*types.Basic)
		if !ok || key.Kind() != types.String {
			return nil, fmt.Errorf("map key type must be string, found %s", value.Key())
		}
		var keyPlan *decodePlan
		if g.implements(value.Key(), g.cursorDecoder) {
			keyPlan = &decodePlan{typ: value.Key(), kind: decodeCursorUnmarshaler}
		} else if g.implements(value.Key(), g.unmarshaler) {
			keyPlan = &decodePlan{typ: value.Key(), kind: decodeUnmarshaler}
		}
		elem, err := g.analyzeType(value.Elem())
		return &decodePlan{
			typ: t, kind: decodeMap, key: value.Key(), keyPlan: keyPlan, elem: elem,
		}, err
	default:
		return nil, fmt.Errorf("unsupported type %s", t)
	}
}

func supportedBasic(basic *types.Basic) error {
	switch basic.Kind() {
	case types.Bool, types.String,
		types.Int, types.Int8, types.Int16, types.Int32, types.Int64,
		types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64,
		types.Float32, types.Float64:
		return nil
	default:
		return fmt.Errorf("unsupported type %s", basic)
	}
}

func maxminddbTag(raw string) (maxminddbtag.Options, bool, error) {
	for raw != "" {
		i := 0
		for i < len(raw) && raw[i] == ' ' {
			i++
		}
		raw = raw[i:]
		if raw == "" {
			break
		}

		i = 0
		for i < len(raw) && raw[i] > ' ' && raw[i] != ':' && raw[i] != '"' && raw[i] != 0x7f {
			i++
		}
		if i == 0 || i+1 >= len(raw) || raw[i] != ':' || raw[i+1] != '"' {
			if raw[:i] == maxminddbTagKey {
				return maxminddbtag.Options{}, false, errors.New(
					"malformed maxminddb struct tag",
				)
			}
			next := strings.IndexByte(raw, ' ')
			if next < 0 {
				break
			}
			raw = raw[next+1:]
			continue
		}
		name := raw[:i]
		raw = raw[i+1:]

		i = 1
		for i < len(raw) && raw[i] != '"' {
			if raw[i] == '\\' {
				i++
			}
			i++
		}
		if i >= len(raw) {
			if name == maxminddbTagKey {
				return maxminddbtag.Options{}, false, errors.New(
					"unterminated maxminddb struct tag",
				)
			}
			break
		}
		quotedValue := raw[:i+1]
		raw = raw[i+1:]
		if name != maxminddbTagKey {
			continue
		}
		if !utf8.ValidString(quotedValue) {
			return maxminddbtag.Options{}, false, errors.New(
				"invalid UTF-8 maxminddb struct tag",
			)
		}
		value, err := strconv.Unquote(quotedValue)
		if err != nil {
			return maxminddbtag.Options{}, false, fmt.Errorf(
				"invalid maxminddb struct tag: %w",
				err,
			)
		}
		if !utf8.ValidString(value) {
			return maxminddbtag.Options{}, false, errors.New(
				"invalid UTF-8 maxminddb struct tag",
			)
		}
		options, err := maxminddbtag.Parse(value)
		if err != nil {
			return maxminddbtag.Options{}, false, fmt.Errorf(
				"invalid maxminddb struct tag: %w",
				err,
			)
		}
		return options, true, nil
	}
	return maxminddbtag.Options{}, false, nil
}

func maxSizeKindForPlan(plan *decodePlan) (decodeKind, bool) {
	for plan.kind == decodePointer {
		plan = plan.elem
	}
	switch plan.kind {
	case decodeBytes, decodeSlice, decodeMap:
		return plan.kind, true
	case decodeBasic:
		if plan.basic.Kind() == types.String {
			return decodeBasic, true
		}
	case decodeCursorUnmarshaler, decodeUnmarshaler:
		return maxSizeKindForType(plan.typ)
	default:
	}
	return 0, false
}

func isCustomUnmarshalerPlan(plan *decodePlan) bool {
	for plan.kind == decodePointer {
		plan = plan.elem
	}
	return plan.kind == decodeCursorUnmarshaler || plan.kind == decodeUnmarshaler
}

func maxSizeKindForType(t types.Type) (decodeKind, bool) {
	for {
		pointer, ok := t.(*types.Pointer)
		if !ok {
			break
		}
		t = pointer.Elem()
	}
	switch underlying := t.Underlying().(type) {
	case *types.Basic:
		if underlying.Kind() == types.String {
			return decodeBasic, true
		}
	case *types.Map:
		return decodeMap, true
	case *types.Slice:
		if types.Identical(t, types.NewSlice(types.Typ[types.Byte])) {
			return decodeBytes, true
		}
		return decodeSlice, true
	default:
	}
	return 0, false
}

func lookupUnmarshalMethod(named *types.Named) *types.Func {
	return lookupMethod(named, "UnmarshalMaxMindDB")
}

func lookupCursorUnmarshalMethod(named *types.Named) *types.Func {
	return lookupMethod(named, "UnmarshalMaxMindDBCursor")
}

func lookupMethod(named *types.Named, name string) *types.Func {
	selection := types.NewMethodSet(types.NewPointer(named)).Lookup(nil, name)
	if selection == nil {
		return nil
	}
	method, _ := selection.Obj().(*types.Func)
	return method
}

func packageInterface(pkg *types.Package, name string) (*types.Interface, error) {
	object := pkg.Scope().Lookup(name)
	if object == nil {
		return nil, fmt.Errorf("%s does not declare %s", pkg.Path(), name)
	}
	iface, ok := object.Type().Underlying().(*types.Interface)
	if !ok {
		return nil, fmt.Errorf("%s.%s is not an interface", pkg.Path(), name)
	}
	return iface.Complete(), nil
}

func (g *generator) implements(t types.Type, iface *types.Interface) bool {
	named := t
	if pointer, ok := named.(*types.Pointer); ok {
		named = pointer.Elem()
	}
	if named, ok := named.(*types.Named); ok && named.Obj().Pkg() == g.pkg.Types {
		var method *types.Func
		switch iface {
		case g.unmarshaler:
			method = lookupUnmarshalMethod(named)
		case g.cursorDecoder:
			method = lookupCursorUnmarshalMethod(named)
		default:
		}
		if g.isGeneratedMethod(method) {
			return false
		}
	}
	if types.Implements(t, iface) {
		return true
	}
	if _, ok := t.(*types.Pointer); ok {
		return false
	}
	return types.Implements(types.NewPointer(t), iface)
}

func (g *generator) isGeneratedMethod(method *types.Func) bool {
	if method == nil {
		return false
	}
	filename := filepath.Clean(g.pkg.Fset.Position(method.Pos()).Filename)
	return g.generatedFiles[filename]
}

func encodeHelperNamespace(output string) string {
	const hex = "0123456789abcdef"
	stem := strings.TrimSuffix(filepath.Base(output), filepath.Ext(output))
	var encoded strings.Builder
	for i := range len(stem) {
		value := stem[i]
		if value >= 'a' && value <= 'z' || value >= 'A' && value <= 'Z' ||
			value >= '0' && value <= '9' {
			encoded.WriteByte(value)
			continue
		}
		encoded.WriteByte('_')
		encoded.WriteByte(hex[value>>4])
		encoded.WriteByte(hex[value&0x0f])
	}
	return encoded.String()
}

func (g *generator) helperName(named *types.Named) string {
	if g.targetSet[named] {
		return "maxminddbGenDecode" + named.Obj().Name()
	}
	return "maxminddbGen_" + g.helperNamespace + "_Decode" + named.Obj().Name()
}

func (g *generator) validateHelperNames() error {
	reserved := make(map[string]struct{}, len(g.structs)+2)
	reserve := func(name string, pos token.Pos) error {
		if _, ok := reserved[name]; ok {
			return fmt.Errorf("generated helper %s collides with another generated helper", name)
		}
		reserved[name] = struct{}{}
		if g.pkg.Types.Scope().Lookup(name) == nil {
			return nil
		}
		if pos.IsValid() {
			return g.positionError(
				pos,
				"generated helper %s collides with an existing declaration",
				name,
			)
		}
		return fmt.Errorf("generated helper %s collides with an existing declaration", name)
	}

	namedTypes := make([]*types.Named, 0, len(g.structs))
	for named := range g.structs {
		namedTypes = append(namedTypes, named)
	}
	slices.SortFunc(namedTypes, func(a, b *types.Named) int {
		return strings.Compare(a.Obj().Name(), b.Obj().Name())
	})
	for _, named := range namedTypes {
		if err := reserve(g.helperName(named), named.Obj().Pos()); err != nil {
			return err
		}
	}
	for _, helper := range g.inferred {
		if err := reserve(helper.name, token.NoPos); err != nil {
			return err
		}
	}
	for _, info := range g.structs {
		for _, field := range info.fields {
			if plan := findDecodeBytesPlan(field.plan); plan != nil {
				g.byteSlicePlan = plan
				break
			}
		}
		if g.byteSlicePlan != nil {
			break
		}
	}
	if g.byteSlicePlan != nil {
		// The shared helper operates on []byte, regardless of field aliases.
		byteType := types.Universe.Lookup("byte").Type().(*types.Basic)
		g.byteSlicePlan = &decodePlan{
			typ: types.NewSlice(byteType), kind: decodeBytes,
			elem: &decodePlan{typ: byteType, kind: decodeBasic, basic: byteType},
		}
		for _, name := range []string{g.bytesHelperName(), g.byteSliceHelperName()} {
			if err := reserve(name, token.NoPos); err != nil {
				return err
			}
		}
	}
	return nil
}

func findDecodeBytesPlan(plan *decodePlan) *decodePlan {
	if plan.kind == decodeBytes {
		return plan
	}
	switch plan.kind {
	case decodePointer, decodeSlice, decodeMap:
		return findDecodeBytesPlan(plan.elem)
	default:
		return nil
	}
}

func (g *generator) byteSliceHelperName() string {
	return "maxminddbGen_" + g.helperNamespace + "_ByteSlice"
}

func (g *generator) bytesHelperName() string {
	return "maxminddbGen_" + g.helperNamespace + "_Bytes"
}

func (g *generator) render(buildConstraint string) ([]byte, error) {
	source := g.renderSource(buildConstraint)
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w\n%s", err, source)
	}
	return formatted, nil
}

// renderSource returns the generated file before formatting.
func (g *generator) renderSource(buildConstraint string) string {
	var body strings.Builder
	mmdbdata := g.importNames[mmdbdataPath]
	infos := make([]structInfo, 0, len(g.structs))
	for _, info := range g.structs {
		infos = append(infos, info)
	}
	slices.SortFunc(infos, func(a, b structInfo) int {
		return strings.Compare(a.named.Obj().Name(), b.named.Obj().Name())
	})
	for _, info := range infos {
		g.emitStruct(&body, info)
	}
	for _, helper := range g.inferred {
		g.emitInferredDecoder(&body, helper)
	}
	if g.byteSlicePlan != nil {
		g.emitByteSliceHelper(&body)
	}
	receiverName := g.local("out")
	cursorName := g.local("cursor")
	decoderName := g.local("decoder")
	nextName := g.local("next")
	errName := g.local("err")
	for _, target := range g.targets {
		fmt.Fprintf(
			&body,
			"func (%s *%s) UnmarshalMaxMindDBCursor(%s %s.Cursor) (%s.Cursor, error) {\n",
			receiverName,
			g.typeString(target),
			cursorName,
			mmdbdata,
			mmdbdata,
		)
		fmt.Fprintf(&body, "\treturn %s(%s, %s)\n", g.helperName(target), cursorName, receiverName)
		body.WriteString("}\n\n")

		fmt.Fprintf(
			&body,
			"func (%s *%s) UnmarshalMaxMindDB(%s *%s.Decoder) error {\n",
			receiverName,
			g.typeString(target),
			decoderName,
			mmdbdata,
		)
		fmt.Fprintf(
			&body,
			"\t%s, %s := %s(%s.Cursor(), %s)\n",
			nextName,
			errName,
			g.helperName(target),
			decoderName,
			receiverName,
		)
		fmt.Fprintf(&body, "\tif %s != nil {\n\t\treturn %s\n\t}\n", errName, errName)
		fmt.Fprintf(&body, "\treturn %s.Advance(%s)\n}\n\n", decoderName, nextName)
	}

	var source strings.Builder
	if buildConstraint != "" {
		fmt.Fprintf(&source, "//go:build %s\n\n", buildConstraint)
	}
	fmt.Fprintf(&source, "%s; DO NOT EDIT.\n", generatedPrefix)
	fmt.Fprintf(
		&source,
		"// Requires github.com/oschwald/maxminddb-golang/v2 %s or newer.\n\n",
		minimumLibrary,
	)
	fmt.Fprintf(&source, "package %s\n\n", g.pkg.Name)
	g.emitImports(&source)
	source.WriteString(body.String())
	return source.String()
}

func (g *generator) emitStruct(out *strings.Builder, info structInfo) {
	mmdbdata := g.importNames[mmdbdataPath]
	cursor := g.local("cursor")
	receiver := g.local("out")
	entries := g.local("entries")
	errName := g.local("err")
	next := g.local("next")
	key := g.local("key")
	valueCursor := g.local("valueCursor")
	keyErr := g.local("keyErr")
	fmt.Fprintf(
		out,
		"func %s(%s %s.Cursor, %s *%s) (%s.Cursor, error) {\n",
		g.helperName(info.named),
		cursor,
		mmdbdata,
		receiver,
		g.typeString(info.named),
		mmdbdata,
	)
	fmt.Fprintf(out, "\t%s, %s := %s.MapReader()\n", entries, errName, cursor)
	fmt.Fprintf(
		out,
		"\tif %s != nil {\n\t\treturn %s.Cursor{}, %s.NormalizeUnmarshalError[%s](%s)\n\t}\n",
		errName,
		mmdbdata,
		mmdbdata,
		g.typeString(info.named),
		errName,
	)
	fmt.Fprintf(out, "\t%s := %s.First()\n", next, entries)
	seenFields := g.seenFieldsName
	if len(info.fields) != 0 {
		if len(info.fields) <= 64 {
			fmt.Fprintf(out, "\tvar %s uint64\n", seenFields)
		} else {
			fmt.Fprintf(out, "\tvar %s [%d]uint64\n", seenFields, (len(info.fields)+63)/64)
		}
	}
	fmt.Fprintf(out, "\tfor range %s.Len() {\n", entries)
	fmt.Fprintf(out, "\t\t%s, %s, %s := %s.ReadMapKey()\n", key, valueCursor, keyErr, next)
	fmt.Fprintf(
		out,
		"\t\tif %s != nil {\n\t\t\treturn %s.Cursor{}, %s\n\t\t}\n",
		keyErr,
		mmdbdata,
		keyErr,
	)
	fmt.Fprintf(out, "\t\tswitch string(%s) {\n", key)
	for fieldIndex, field := range info.fields {
		fmt.Fprintf(out, "\t\tcase %s:\n", strconv.Quote(field.name))
		seenField := seenFields
		if len(info.fields) > 64 {
			seenField = fmt.Sprintf("%s[%d]", seenFields, fieldIndex/64)
		}
		fieldBit := uint64(1) << (fieldIndex % 64)
		fmt.Fprintf(out, "\t\t\tif %s&%d != 0 {\n", seenField, fieldBit)
		fmt.Fprintf(
			out,
			"\t\t\t\treturn %s.Cursor{}, %s.NewInvalidDatabaseError(\"duplicate map key %%q\", %s)\n",
			mmdbdata,
			mmdbdata,
			key,
		)
		out.WriteString("\t\t\t}\n")
		fmt.Fprintf(out, "\t\t\t%s |= %d\n", seenField, fieldBit)
		target := receiver + "." + field.goID
		if field.hasMaxSize {
			if !g.emitMaxSizeDecode(
				out,
				field.plan,
				valueCursor,
				target,
				next,
				errName,
				3,
				field.maxSize,
			) {
				fmt.Fprintf(
					out,
					"\t\t\tif %s = %s.CheckMaxSize(%s, %d); %s == nil {\n",
					errName,
					valueCursor,
					g.maxSizeKindExpression(field.plan, field.maxSizeKind),
					field.maxSize,
					errName,
				)
				g.emitDecode(out, field.plan, valueCursor, target, next, errName, 4)
				out.WriteString("\t\t\t}\n")
			}
		} else {
			g.emitDecode(out, field.plan, valueCursor, target, next, errName, 3)
		}
		errorFormat := "decoding field " + strings.ReplaceAll(field.name, "%", "%%") + ": %w"
		fmt.Fprintf(
			out,
			"\t\t\tif %s != nil {\n\t\t\t\treturn %s.Cursor{}, %s.Errorf(%s, %s)\n\t\t\t}\n",
			errName,
			mmdbdata,
			g.importNames[fmtPath],
			strconv.Quote(errorFormat),
			g.errorExpression(field.plan, errName),
		)
	}
	fmt.Fprintf(
		out,
		"\t\tdefault:\n\t\t\t%s, %s = %s.Skip()\n\t\t}\n",
		next,
		errName,
		valueCursor,
	)
	fmt.Fprintf(
		out,
		"\t\tif %s != nil {\n\t\t\treturn %s.Cursor{}, %s\n\t\t}\n",
		errName,
		mmdbdata,
		errName,
	)
	out.WriteString("\t}\n")
	fmt.Fprintf(out, "\treturn %s.End(%s)\n}\n\n", entries, next)
}

func (g *generator) emitMaxSizeDecode(
	out *strings.Builder,
	plan *decodePlan,
	cursor, target, next, errName string,
	indent int,
	maximum uint64,
) bool {
	if plan.inferred != nil {
		return false
	}
	switch {
	case plan.kind == decodeBasic && plan.basic.Kind() == types.String:
		pad := strings.Repeat("\t", indent)
		value := g.localID("value", g.id())
		fmt.Fprintf(
			out,
			"%svar %s string\n%s%s, %s, %s = %s.ReadStringMaxSize(%d)\n",
			pad,
			value,
			pad,
			value,
			next,
			errName,
			cursor,
			maximum,
		)
		fmt.Fprintf(
			out,
			"%sif %s == nil {\n%s\t%s = %s(%s)\n%s}\n",
			pad,
			errName,
			pad,
			target,
			g.typeString(plan.typ),
			value,
			pad,
		)
		return true
	case plan.kind == decodeSlice:
		g.emitSliceMaxSize(out, plan, cursor, target, next, errName, indent, maximum)
		return true
	default:
		return false
	}
}

func (g *generator) maxSizeKindExpression(plan *decodePlan, kind decodeKind) string {
	mmdbdata := g.importNames[mmdbdataPath]
	if isCustomUnmarshalerPlan(plan) {
		// A custom callback may consume any MMDB encoding regardless of its Go
		// type's underlying shape, so constrain every size-bearing input kind.
		return mmdbdata + ".NewKindSet(" +
			mmdbdata + ".KindMap, " +
			mmdbdata + ".KindSlice, " +
			mmdbdata + ".KindString, " +
			mmdbdata + ".KindBytes)"
	}
	switch kind {
	case decodeBasic:
		return mmdbdata + ".NewKindSet(" + mmdbdata + ".KindString)"
	case decodeBytes:
		return mmdbdata + ".NewKindSet(" + mmdbdata + ".KindBytes, " +
			mmdbdata + ".KindSlice)"
	case decodeSlice:
		return mmdbdata + ".NewKindSet(" + mmdbdata + ".KindSlice)"
	case decodeMap:
		return mmdbdata + ".NewKindSet(" + mmdbdata + ".KindMap)"
	default:
		panic("unsupported maxsize decode kind")
	}
}

func (g *generator) emitDecode(
	out *strings.Builder,
	plan *decodePlan,
	cursor, target, next, errName string,
	indent int,
) {
	pad := strings.Repeat("\t", indent)
	if plan.inferred != nil {
		fmt.Fprintf(
			out,
			"%s%s, %s = %s(%s, &%s)\n",
			pad,
			next,
			errName,
			plan.inferred.name,
			cursor,
			target,
		)
		return
	}
	switch plan.kind {
	case decodePointer:
		decoded := g.localID("decoded", g.id())
		fmt.Fprintf(out, "%sif %s == nil {\n", pad, target)
		fmt.Fprintf(out, "%s\tvar %s %s\n", pad, decoded, g.typeString(plan.elem.typ))
		g.emitDecode(out, plan.elem, cursor, decoded, next, errName, indent+1)
		fmt.Fprintf(
			out,
			"%s\tif %s == nil {\n%s\t\t%s = &%s\n%s\t}\n",
			pad,
			errName,
			pad,
			target,
			decoded,
			pad,
		)
		fmt.Fprintf(out, "%s} else {\n", pad)
		g.emitDecode(
			out,
			plan.elem,
			cursor,
			fmt.Sprintf("(*%s)", target),
			next,
			errName,
			indent+1,
		)
		fmt.Fprintf(out, "%s}\n", pad)
	case decodeCursorUnmarshaler:
		argument := "&" + target
		if plan.unmarshalType != nil {
			argument = g.typeString(plan.unmarshalType) + "(" + argument + ")"
		}
		fmt.Fprintf(
			out,
			"%s%s, %s = %s.UnmarshalCursor(%s)\n",
			pad,
			next,
			errName,
			cursor,
			argument,
		)
	case decodeUnmarshaler:
		argument := "&" + target
		if plan.unmarshalType != nil {
			argument = g.typeString(plan.unmarshalType) + "(" + argument + ")"
		}
		fmt.Fprintf(out, "%s%s, %s = %s.Unmarshal(%s)\n", pad, next, errName, cursor, argument)
	case decodeStruct:
		fmt.Fprintf(
			out,
			"%s%s, %s = %s(%s, &%s)\n",
			pad,
			next,
			errName,
			g.helperName(plan.named),
			cursor,
			target,
		)
	case decodeBasic:
		g.emitBasic(out, plan.typ, plan.basic, cursor, target, next, errName, indent)
	case decodeBytes:
		g.emitBytes(out, cursor, target, next, errName, indent)
	case decodeSlice:
		g.emitSlice(out, plan, cursor, target, next, errName, indent)
	case decodeMap:
		g.emitMap(out, plan, cursor, target, next, errName, indent)
	default:
		panic("unsupported decode plan for " + plan.typ.String())
	}
}

func (g *generator) emitBytes(
	out *strings.Builder,
	cursor, target, next, errName string,
	indent int,
) {
	pad := strings.Repeat("\t", indent)
	fmt.Fprintf(
		out,
		"%s%s, %s, %s = %s(%s, %s)\n",
		pad,
		target,
		next,
		errName,
		g.bytesHelperName(),
		cursor,
		target,
	)
}

func (g *generator) emitByteSliceHelper(out *strings.Builder) {
	mmdbdata := g.importNames[mmdbdataPath]
	cursor := g.local("cursor")
	target := g.local("target")
	decoded := g.local("decoded")
	next := g.local("next")
	errName := g.local("err")
	readErr := g.local("readErr")
	mismatch := g.local("mismatch")
	fmt.Fprintf(
		out,
		"func %s(%s %s.Cursor, %s []byte) ([]byte, %s.Cursor, error) {\n",
		g.bytesHelperName(),
		cursor,
		mmdbdata,
		target,
		mmdbdata,
	)
	fmt.Fprintf(out, "\t%s, %s, %s := %s.ReadBytes()\n", decoded, next, errName, cursor)
	fmt.Fprintf(
		out,
		"\tif %s != nil {\n\t\treturn %s(%s, %s, %s)\n\t}\n",
		errName,
		g.byteSliceHelperName(),
		cursor,
		target,
		errName,
	)
	fmt.Fprintf(
		out,
		"\tif len(%s) == 0 && %s == nil {\n\t\treturn []byte{}, %s, nil\n\t}\n",
		decoded,
		target,
		next,
	)
	fmt.Fprintf(out, "\treturn append(%s[:0], %s...), %s, nil\n}\n\n", target, decoded, next)
	fmt.Fprintf(
		out,
		"func %s(%s %s.Cursor, %s []byte, %s error) ([]byte, %s.Cursor, error) {\n",
		g.byteSliceHelperName(),
		cursor,
		mmdbdata,
		target,
		readErr,
		mmdbdata,
	)
	fmt.Fprintf(out, "\tvar %s %s.UnexpectedKindError\n", mismatch, mmdbdata)
	fmt.Fprintf(
		out,
		"\tif !%s.As(%s, &%s) || %s.Actual != %s.KindSlice {\n",
		g.importNames[errorsPath],
		readErr,
		mismatch,
		mismatch,
		mmdbdata,
	)
	fmt.Fprintf(out, "\t\treturn %s, %s.Cursor{}, %s\n\t}\n", target, mmdbdata, readErr)
	fmt.Fprintf(out, "\tvar %s %s.Cursor\n\tvar %s error\n", next, mmdbdata, errName)
	slicePlan := *g.byteSlicePlan
	slicePlan.kind = decodeSlice
	g.emitSlice(out, &slicePlan, cursor, target, next, errName, 1)
	fmt.Fprintf(out, "\treturn %s, %s, %s\n}\n\n", target, next, errName)
}

func (g *generator) emitBasic(
	out *strings.Builder,
	original types.Type,
	basic *types.Basic,
	cursor, target, next, errName string,
	indent int,
) {
	pad := strings.Repeat("\t", indent)
	typeName := g.typeString(original)
	id := g.id()
	switch basic.Kind() {
	case types.String, types.Bool:
		value := g.localID("value", id)
		valueType := "string"
		readMethod := "ReadString"
		if basic.Kind() == types.Bool {
			valueType = "bool"
			readMethod = "ReadBool"
		}
		fmt.Fprintf(
			out,
			"%svar %s %s\n%s%s, %s, %s = %s.%s()\n",
			pad,
			value,
			valueType,
			pad,
			value,
			next,
			errName,
			cursor,
			readMethod,
		)
		fmt.Fprintf(
			out,
			"%sif %s == nil {\n%s\t%s = %s(%s)\n%s}\n",
			pad,
			errName,
			pad,
			target,
			typeName,
			value,
			pad,
		)
	case types.Float32, types.Float64:
		value := g.localID("value", id)
		converted := g.localID("converted", id)
		fmt.Fprintf(
			out,
			"%svar %s float64\n%s%s, %s, %s = %s.ReadFloat()\n",
			pad,
			value,
			pad,
			value,
			next,
			errName,
			cursor,
		)
		fmt.Fprintf(
			out,
			"%sif %s == nil {\n%s\t%s := %s(%s)\n",
			pad,
			errName,
			pad,
			converted,
			typeName,
			value,
		)
		if basic.Kind() == types.Float32 {
			fmt.Fprintf(
				out,
				"%s\tif %s.Abs(%s) > %s.MaxFloat32 && !%s.IsInf(%s, 0) {\n",
				pad,
				g.importNames[mathPath],
				value,
				g.importNames[mathPath],
				g.importNames[mathPath],
				value,
			)
			fmt.Fprintf(
				out,
				"%s\t\t%s = %s.NewUnmarshalTypeError[%s](%s)\n%s\t} else {\n%s\t\t%s = %s\n%s\t}\n",
				pad,
				errName,
				g.importNames[mmdbdataPath],
				typeName,
				value,
				pad,
				pad,
				target,
				converted,
				pad,
			)
		} else {
			fmt.Fprintf(out, "%s\t%s = %s\n", pad, target, converted)
		}
		fmt.Fprintf(out, "%s}\n", pad)
	case types.Int, types.Int8, types.Int16, types.Int32, types.Int64,
		types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64:
		g.emitInteger(out, original, basic, cursor, target, next, errName, indent, id)
	default:
		panic("unsupported basic type")
	}
}

func (g *generator) emitInteger(
	out *strings.Builder,
	original types.Type,
	basic *types.Basic,
	cursor, target, next, errName string,
	indent, id int,
) {
	pad := strings.Repeat("\t", indent)
	typeName := g.typeString(original)
	signed := basic.Info()&types.IsInteger != 0 && basic.Info()&types.IsUnsigned == 0
	integerValue := g.localID("integerValue", id)
	integerSigned := g.localID("integerSigned", id)
	signedValue := g.localID("signedValue", id)
	unsignedValue := g.localID("unsignedValue", id)
	converted := g.localID("converted", id)
	fmt.Fprintf(out, "%svar %s uint64\n", pad, integerValue)
	fmt.Fprintf(out, "%svar %s bool\n", pad, integerSigned)
	fmt.Fprintf(
		out,
		"%s%s, %s, %s, %s = %s.ReadInteger()\n",
		pad,
		integerValue,
		integerSigned,
		next,
		errName,
		cursor,
	)
	fmt.Fprintf(
		out,
		"%sif %s == nil && %s {\n%s\t%s := int64(%s)\n%s\t%s := %s(%s)\n",
		pad,
		errName,
		integerSigned,
		pad,
		signedValue,
		integerValue,
		pad,
		converted,
		typeName,
		signedValue,
	)
	if signed {
		fmt.Fprintf(out, "%s\tif int64(%s) != %s {\n", pad, converted, signedValue)
	} else {
		fmt.Fprintf(
			out,
			"%s\tif %s < 0 || uint64(%s) != uint64(%s) {\n",
			pad,
			signedValue,
			converted,
			signedValue,
		)
	}
	fmt.Fprintf(
		out,
		"%s\t\t%s = %s.NewUnmarshalTypeError[%s](%s)\n%s\t} else {\n%s\t\t%s = %s\n%s\t}\n%s} else if %s == nil {\n",
		pad,
		errName,
		g.importNames[mmdbdataPath],
		typeName,
		signedValue,
		pad,
		pad,
		target,
		converted,
		pad,
		pad,
		errName,
	)
	fmt.Fprintf(out, "%s\t%s := %s\n", pad, unsignedValue, integerValue)
	fmt.Fprintf(out, "%s\t%s := %s(%s)\n", pad, converted, typeName, unsignedValue)
	if signed {
		fmt.Fprintf(
			out,
			"%s\tif %s < 0 || uint64(%s) != %s {\n",
			pad,
			converted,
			converted,
			unsignedValue,
		)
	} else {
		fmt.Fprintf(out, "%s\tif uint64(%s) != %s {\n", pad, converted, unsignedValue)
	}
	fmt.Fprintf(
		out,
		"%s\t\t%s = %s.NewUnmarshalTypeError[%s](%s)\n%s\t} else {\n%s\t\t%s = %s\n%s\t}\n%s}\n",
		pad,
		errName,
		g.importNames[mmdbdataPath],
		typeName,
		unsignedValue,
		pad,
		pad,
		target,
		converted,
		pad,
		pad,
	)
}

