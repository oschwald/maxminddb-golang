type generator struct {
	structs         map[*types.Named]structInfo
	visiting        map[*types.Named]bool
	targetSet       map[*types.Named]bool
	generatedFiles  map[string]bool
	importPackages  map[string]*types.Package
	importNames     map[string]string
	pkg             *packages.Package
	mmdbdata        *packages.Package
	unmarshaler     *types.Interface
	cursorDecoder   *types.Interface
	byteSlicePlan   *decodePlan
	inferred        []*inferredDecoder
	reservedNames   map[string]bool
	localNames      map[string]string
	helperNamespace string
	seenFieldsName  string
	// localTypeQualifier, when set, qualifies the target package's types in
	// rendered output. Only checkShadowedBuiltins sets it.
	localTypeQualifier string
	targets            []*types.Named
	nextID             int
	usesErrors         bool
	usesFmt            bool
	usesMath           bool
}

type structInfo struct {
	named  *types.Named
	fields []fieldInfo
}

type fieldInfo struct {
	plan        *decodePlan
	name        string
	goID        string
	maxSize     uint64
	maxSizeKind decodeKind
	hasMaxSize  bool
}

type methodKey struct {
	receiver string
	name     string
}

type priorGeneratedFile struct {
	file *ast.File
	path string
}

type decodeKind uint8

