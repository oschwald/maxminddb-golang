func (g *generator) errorExpression(plan *decodePlan, name string) string {
	if plan.inferred != nil {
		return name
	}
	for plan.kind == decodePointer {
		plan = plan.elem
	}
	if plan.kind == decodeBasic || plan.kind == decodeBytes {
		return fmt.Sprintf(
			"%s.NormalizeUnmarshalError[%s](%s)",
			g.importNames[mmdbdataPath],
			g.typeString(plan.typ),
			name,
		)
	}
	return name
}

// prepareLocalNames records every package-level name that generated code may
// refer to: the package's own declarations, the generated imports, and the
// generated helpers. Locals and parameters must not shadow any of them, or a
// field type with the same name would resolve to the local instead.
func (g *generator) prepareLocalNames() {
	scope := g.pkg.Types.Scope()
	g.reservedNames = make(map[string]bool, scope.Len()+len(g.importNames)+len(g.structs)+2)
	for _, name := range scope.Names() {
		g.reservedNames[name] = true
	}
	for _, name := range g.importNames {
		g.reservedNames[name] = true
	}
	for named := range g.structs {
		g.reservedNames[g.helperName(named)] = true
	}
	for _, helper := range g.inferred {
		g.reservedNames[helper.name] = true
		for _, parameter := range helper.params {
			g.reservedNames[parameter.Obj().Name()] = true
		}
	}
	if g.byteSlicePlan != nil {
		g.reservedNames[g.bytesHelperName()] = true
		g.reservedNames[g.byteSliceHelperName()] = true
	}
	g.localNames = make(map[string]string)
	g.seenFieldsName = "seenFields"
	for suffix := 1; g.reservedNames[g.seenFieldsName]; suffix++ {
		g.seenFieldsName = "seenFields" + strconv.Itoa(suffix)
	}
}

// local returns the name to use for a generated local or parameter. A name
// that is reserved gets trailing underscores until it is free. No requested
// name ends in an underscore, fixed names never end in a digit, and numbered
// names are unique per stem and id, so a renamed name cannot equal another
// generated name.
func (g *generator) local(name string) string {
	if renamed, ok := g.localNames[name]; ok {
		return renamed
	}
	if g.localNames == nil {
		g.localNames = make(map[string]string)
	}
	renamed := name
	for g.reservedNames[renamed] {
		renamed += "_"
	}
	g.localNames[name] = renamed
	return renamed
}

// localID returns the collision-free name for a numbered local such as value3.
func (g *generator) localID(stem string, id int) string {
	return g.local(stem + strconv.Itoa(id))
}

// checkShadowedBuiltins rejects a package-level declaration that shadows a Go
// builtin that generated code relies on, such as a function named clear. Go
// cannot refer to a shadowed builtin, and the output might still compile and
// call the package's declaration instead. The check renders the output once
// with package types qualified by a marker, so every bare identifier left is
// one the generator wrote itself rather than a user type it meant to name.
func (g *generator) checkShadowedBuiltins() error {
	g.localTypeQualifier = "maxminddbGenLocal"
	source := g.renderSource("")
	g.localTypeQualifier = ""
	g.nextID = 0
	file, err := parser.ParseFile(token.NewFileSet(), "", source, parser.SkipObjectResolution)
	if err != nil {
		// The real render reports the problem with the package's own names.
		return nil //nolint:nilerr // Reported by render.
	}
	scope := g.pkg.Types.Scope()
	shadowed := make(map[string]types.Object)
	// Skip the package clause, which names the package rather than a builtin.
	for _, declaration := range file.Decls {
		ast.Inspect(declaration, func(node ast.Node) bool {
			return inspectBuiltinUse(node, scope, shadowed)
		})
	}
	if len(shadowed) == 0 {
		return nil
	}
	names := make([]string, 0, len(shadowed))
	for name := range shadowed {
		names = append(names, name)
	}
	slices.Sort(names)
	errs := make([]error, 0, len(names))
	for _, name := range names {
		errs = append(errs, g.positionError(
			shadowed[name].Pos(),
			"declaration of %s shadows the Go builtin that generated code uses; rename it",
			name,
		))
	}
	return errors.Join(errs...)
}

func inspectBuiltinUse(node ast.Node, scope *types.Scope, shadowed map[string]types.Object) bool {
	switch node := node.(type) {
	case *ast.SelectorExpr:
		// Only the operand can name a builtin; the selector names a member.
		ast.Inspect(node.X, func(child ast.Node) bool {
			return inspectBuiltinUse(child, scope, shadowed)
		})
		return false
	case *ast.Field:
		// Only the type can name a builtin; the names declare parameters,
		// struct fields, or methods, such as a field in a type argument.
		if node.Type != nil {
			ast.Inspect(node.Type, func(child ast.Node) bool {
				return inspectBuiltinUse(child, scope, shadowed)
			})
		}
		return false
	case *ast.Ident:
		builtin := types.Universe.Lookup(node.Name)
		if builtin == nil {
			return false
		}
		object := scope.Lookup(node.Name)
		if object == nil {
			return false
		}
		// An alias such as `type byte = uint8` names the builtin's own type.
		if _, ok := object.(*types.TypeName); ok {
			if _, ok := builtin.(*types.TypeName); ok &&
				types.Identical(object.Type(), builtin.Type()) {
				return false
			}
		}
		shadowed[node.Name] = object
		return false
	default:
		return true
	}
}

func (g *generator) id() int {
	g.nextID++
	return g.nextID
}

func (g *generator) typeString(t types.Type) string {
	return types.TypeString(t, func(pkg *types.Package) string {
		if pkg == g.pkg.Types {
			return g.localTypeQualifier
		}
		name, ok := g.importNames[pkg.Path()]
		if !ok {
			panic("missing generated import for " + pkg.Path())
		}
		return name
	})
}

func (g *generator) prepareImports() {
	for _, info := range g.structs {
		if len(info.fields) > 0 {
			g.usesFmt = true
		}
		for _, field := range info.fields {
			g.collectPlanImports(field.plan, false)
			g.usesMath = g.usesMath || planUsesFloat32(field.plan)
		}
	}
	g.usesErrors = g.byteSlicePlan != nil

	paths := make([]string, 0, len(g.importPackages))
	for path := range g.importPackages {
		if path != mmdbdataPath {
			paths = append(paths, path)
		}
	}
	slices.Sort(paths)

	used := make(map[string]bool, len(paths)+4)
	nextGeneratedName := 1
	available := func(name string) bool {
		return !used[name] && g.pkg.Types.Scope().Lookup(name) == nil
	}
	generatedName := func() string {
		for {
			name := "_maxminddbgenImport" + strconv.Itoa(nextGeneratedName)
			nextGeneratedName++
			if available(name) {
				return name
			}
		}
	}
	reserve := func(path, preferred string) {
		name := preferred
		if !available(name) {
			name = generatedName()
		}
		g.importNames[path] = name
		used[name] = true
	}

	if g.usesErrors {
		reserve(errorsPath, "errors")
	}
	if g.usesFmt {
		reserve(fmtPath, "fmt")
	}
	if g.usesMath {
		reserve(mathPath, "math")
	}
	reserve(mmdbdataPath, "mmdbdata")
	for _, path := range paths {
		name := generatedName()
		g.importNames[path] = name
		used[name] = true
	}
}

func planUsesFloat32(plan *decodePlan) bool {
	if plan.kind == decodeBasic && plan.basic.Kind() == types.Float32 {
		return true
	}
	switch plan.kind {
	case decodePointer, decodeSlice, decodeMap:
		return planUsesFloat32(plan.elem)
	default:
		return false
	}
}

func (g *generator) collectPlanImports(plan *decodePlan, typeRequired bool) {
	if helper := plan.inferred; helper != nil {
		g.collectPlanImports(helper.plan, false)
		for _, parameter := range helper.params {
			g.collectTypeImports(parameter.Constraint())
		}
		return
	}
	if typeRequired || plan.kind == decodeBasic || plan.kind == decodeBytes ||
		plan.kind == decodeSlice ||
		plan.kind == decodeMap {
		g.collectTypeImports(plan.typ)
	}
	switch plan.kind {
	case decodePointer, decodeSlice:
		g.collectPlanImports(plan.elem, true)
	case decodeMap:
		g.collectTypeImports(plan.key)
		g.collectPlanImports(plan.elem, true)
	default:
	}
}

func (g *generator) collectTypeImports(t types.Type) {
	types.TypeString(t, func(pkg *types.Package) string {
		if pkg != g.pkg.Types {
			g.importPackages[pkg.Path()] = pkg
		}
		return pkg.Name()
	})
}

type generatedImport struct {
	path string
	name string
}

func isThirdPartyImport(path string) bool {
	first, _, _ := strings.Cut(path, "/")
	return strings.Contains(first, ".")
}

func (g *generator) emitImports(source *strings.Builder) {
	imports := make([]generatedImport, 0, len(g.importPackages)+4)
	if g.usesErrors {
		imports = append(imports, g.importSpec(errorsPath))
	}
	if g.usesFmt {
		imports = append(imports, g.importSpec(fmtPath))
	}
	if g.usesMath {
		imports = append(imports, g.importSpec(mathPath))
	}
	for path := range g.importPackages {
		if path == mmdbdataPath {
			continue
		}
		imports = append(imports, g.importSpec(path))
	}
	imports = append(imports, g.importSpec(mmdbdataPath))
	slices.SortFunc(imports, func(a, b generatedImport) int {
		aThirdParty := isThirdPartyImport(a.path)
		bThirdParty := isThirdPartyImport(b.path)
		if aThirdParty != bThirdParty {
			if aThirdParty {
				return 1
			}
			return -1
		}
		return strings.Compare(a.path, b.path)
	})

	source.WriteString("import (\n")
	thirdParty := false
	for _, generatedImport := range imports {
		if isThirdPartyImport(generatedImport.path) && !thirdParty {
			if generatedImport.path != imports[0].path {
				source.WriteString("\n")
			}
			thirdParty = true
		}
		source.WriteString("\t")
		if generatedImport.name != "" {
			source.WriteString(generatedImport.name)
			source.WriteString(" ")
		}
		source.WriteString(strconv.Quote(generatedImport.path))
		source.WriteString("\n")
	}
	source.WriteString(")\n\n")
}

func (g *generator) importSpec(path string) generatedImport {
	name := g.importNames[path]
	defaultName := path
	if index := strings.LastIndexByte(defaultName, '/'); index >= 0 {
		defaultName = defaultName[index+1:]
	}
	if name == defaultName {
		name = ""
	}
	return generatedImport{path: path, name: name}
}

func (g *generator) positionError(pos token.Pos, formatString string, args ...any) error {
	position := g.pkg.Fset.Position(pos)
	if !position.IsValid() {
		return fmt.Errorf(formatString, args...)
	}
	return fmt.Errorf("%s: %s", position, fmt.Sprintf(formatString, args...))
}
